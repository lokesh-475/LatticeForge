#!/usr/bin/env python3
"""
LatticeForge Shell Thickness Analytics & Radial Profile Visualizer

Quantitative characterization of core-shell solute segregation in discrete
polycrystalline microstructures.

Physics Reference:
    Ma et al., "Microstructure evolution and magnetic properties of Multi-Main-Phase
    Nd-Ce-Fe-B permanent magnets," Journal of Alloys and Compounds (2025).

Functions:
    - Reads outputs/radial_profile.csv generated by C++ LatticeForge engine
    - Computes quantitative shell thickness via half-maximum (C50) threshold interpolation
    - Computes integral breadth thickness and interfacial segregation gradient
    - Generates publication-quality dual-panel radial concentration plots
"""

import os
import sys
import csv
import subprocess
import numpy as np
import matplotlib.pyplot as plt

def get_project_paths():
    """Resolves project paths relative to this script."""
    tool_dir = os.path.dirname(os.path.abspath(__file__))
    python_dir = os.path.dirname(tool_dir)
    root_dir = os.path.dirname(python_dir)
    outputs_dir = os.path.join(root_dir, 'outputs')
    os.makedirs(outputs_dir, exist_ok=True)
    return root_dir, outputs_dir

def load_or_generate_radial_profile(outputs_dir, root_dir):
    """Loads radial_profile.csv, running the engine if missing."""
    csv_path = os.path.join(outputs_dir, 'radial_profile.csv')
    
    if not os.path.exists(csv_path):
        print(f"Radial profile not found at {csv_path}. Attempting to execute C++ engine...")
        
        # Try running CUDA or CPU binary
        candidates = [
            os.path.join(root_dir, 'lattice_forge_cuda.exe'),
            os.path.join(root_dir, 'build', 'lattice_forge_cuda.exe'),
            os.path.join(root_dir, 'lattice_forge.exe'),
            os.path.join(root_dir, 'build', 'lattice_forge.exe'),
        ]
        
        executed = False
        for exe in candidates:
            if os.path.exists(exe):
                print(f"Executing engine binary: {exe}...")
                res = subprocess.run([exe, "30"], cwd=root_dir, capture_output=True, text=True)
                if res.returncode == 0 and os.path.exists(csv_path):
                    executed = True
                    break
        
        if not executed:
            # Fallback to python prototype
            print("Engine executable not found or failed; using Python prototype simulation fallback...")
            python_dir = os.path.join(root_dir, 'python')
            if python_dir not in sys.path:
                sys.path.insert(0, python_dir)
            from prototypes.prototype_sim import LatticeForgePrototype, SimulationConfig
            
            cfg = SimulationConfig(size=128, temp=0.4, seed=42)
            sim = LatticeForgePrototype(cfg)
            sim.initialize_voronoi(num_grains=36, fraction_ce=0.30)
            print("Simulating 35 coupled Potts-Kawasaki MCS steps...")
            for _ in range(35):
                sim.step(potts_mc_sweeps=1, kawasaki_mc_sweeps=1)
                
            # Compute radial profile in python
            L = sim.size
            y_grid, x_grid = np.indices((L, L))
            unique_grains = np.unique(sim.grain_id)
            
            samples_r = []
            samples_c = []
            r_effs = []
            
            for gid in unique_grains:
                mask = (sim.grain_id == gid)
                n_sites = np.sum(mask)
                if n_sites < 10:
                    continue
                r_eff = np.sqrt(n_sites / np.pi)
                r_effs.append(r_eff)
                
                # Circular mean for toroidal coordinates
                ys, xs = y_grid[mask], x_grid[mask]
                theta_x = xs * (2.0 * np.pi / L)
                theta_y = ys * (2.0 * np.pi / L)
                cx = (np.arctan2(np.sum(np.sin(theta_x)), np.sum(np.cos(theta_x))) % (2.0 * np.pi)) * (L / (2.0 * np.pi))
                cy = (np.arctan2(np.sum(np.sin(theta_y)), np.sum(np.cos(theta_y))) % (2.0 * np.pi)) * (L / (2.0 * np.pi))
                
                dx = np.abs(xs - cx)
                dx = np.minimum(dx, L - dx)
                dy = np.abs(ys - cy)
                dy = np.minimum(dy, L - dy)
                r = np.sqrt(dx * dx + dy * dy)
                
                samples_r.extend(r)
                samples_c.extend(sim.element_type[mask])
                
            samples_r = np.array(samples_r)
            samples_c = np.array(samples_c)
            avg_r = np.mean(r_effs)
            
            bin_width = 0.5
            max_r = np.max(samples_r)
            bins = np.arange(0, max_r + bin_width, bin_width)
            
            with open(csv_path, 'w', newline='') as f:
                writer = csv.writer(f)
                writer.writerow(['radial_distance', 'ce_concentration', 'sample_count', 'std_error', 'normalized_distance'])
                for i in range(len(bins) - 1):
                    in_bin = (samples_r >= bins[i]) & (samples_r < bins[i+1])
                    cnt = np.sum(in_bin)
                    if cnt >= 4:
                        conc = float(np.mean(samples_c[in_bin]))
                        err = float(np.sqrt(conc * (1.0 - conc) / cnt))
                        r_mid = float(0.5 * (bins[i] + bins[i+1]))
                        writer.writerow([f"{r_mid:.4f}", f"{conc:.6f}", cnt, f"{err:.6f}", f"{r_mid/avg_r:.4f}"])
            print(f"Fallback generated radial profile written to {csv_path}")

    # Read CSV
    radial_dist = []
    concentration = []
    counts = []
    std_errs = []
    norm_dist = []
    
    with open(csv_path, 'r', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Handle potential alternate column names gracefully
            r_val = float(row.get('radial_distance', row.get('distance', row.get('radius', 0.0))))
            c_val = float(row.get('ce_concentration', row.get('concentration', row.get('c_ce', 0.0))))
            n_val = int(row.get('sample_count', row.get('count', 1)))
            e_val = float(row.get('std_error', row.get('error', 0.0)))
            norm_val = float(row.get('normalized_distance', row.get('norm_r', r_val / 12.0)))
            
            radial_dist.append(r_val)
            concentration.append(c_val)
            counts.append(n_val)
            std_errs.append(e_val)
            norm_dist.append(norm_val)
            
    return (np.array(radial_dist), np.array(concentration), 
            np.array(counts), np.array(std_errs), np.array(norm_dist))

def calculate_shell_thickness_quantitative(r, c, counts=None, norm_r=None):
    """
    Computes quantitative shell thickness via:
      1. C50 half-maximum threshold crossing (linear spline interpolation)
      2. Integral breadth thickness
      3. Steepest interfacial gradient inflection
    """
    # 1. Identify bulk core and boundary peak within representative domain
    if counts is not None and len(counts) > 0:
        max_counts = np.max(counts)
        rep_mask = (counts >= max(20, 0.08 * max_counts))
        if norm_r is not None and len(norm_r) > 0:
            rep_mask &= (norm_r <= 1.8)
    else:
        rep_mask = np.ones_like(r, dtype=bool)

    if not np.any(rep_mask):
        rep_mask = np.ones_like(r, dtype=bool)

    r_max = np.max(r[rep_mask])
    core_mask = (r <= 0.35 * r_max) & rep_mask
    c_core = float(np.min(c[core_mask])) if np.any(core_mask) else float(c[0])
    
    # Peak index within representative domain
    rep_indices = np.where(rep_mask)[0]
    peak_sub_idx = int(np.argmax(c[rep_indices]))
    peak_idx = int(rep_indices[peak_sub_idx])
    c_peak = float(c[peak_idx])
    r_peak = float(r[peak_idx])
    
    # 2. C50 Threshold (Half-Maximum)
    delta_c = c_peak - c_core
    c_thresh = c_core + 0.5 * delta_c
    
    # 3. Find inner shell radius by linear interpolation
    r_inner = 0.0
    found_cross = False
    for i in range(peak_idx):
        if c[i] <= c_thresh and c[i+1] >= c_thresh:
            t = (c_thresh - c[i]) / (c[i+1] - c[i] + 1e-12)
            r_inner = float(r[i] + t * (r[i+1] - r[i]))
            found_cross = True
            break
            
    if not found_cross:
        r_inner = float(r_peak * 0.70)
        
    r_outer = r_peak
    shell_thickness = max(0.0, r_outer - r_inner)
    norm_thickness = (shell_thickness / r_outer) if r_outer > 0 else 0.0
    
    # 4. Integral Breadth Thickness (using robust trapezoidal integration)
    sub_mask = (r <= r_outer)
    if np.sum(sub_mask) >= 2 and delta_c > 1e-6:
        r_sub = r[sub_mask]
        c_sub = np.maximum(0.0, c[sub_mask] - c_core)
        integral_val = float(np.sum(0.5 * (c_sub[:-1] + c_sub[1:]) * np.diff(r_sub)))
        delta_integral = float(integral_val / delta_c)
    else:
        delta_integral = shell_thickness

    # 5. Interfacial Concentration Gradient dC/dr
    dc_dr = np.gradient(c, r)
    grad_peak_idx = int(np.argmax(dc_dr[:peak_idx + 1])) if peak_idx > 0 else 0
    max_gradient = float(dc_dr[grad_peak_idx])
    r_inflection = float(r[grad_peak_idx])
    
    # 6. Geometric 2D Shell Area Fraction: (r_outer^2 - r_inner^2) / r_outer^2
    shell_area_fraction = max(0.0, (r_outer**2 - r_inner**2) / (r_outer**2)) if r_outer > 0 else 0.0
    
    return {
        "c_core": c_core,
        "c_peak": c_peak,
        "c_thresh": c_thresh,
        "r_inner": r_inner,
        "r_outer": r_outer,
        "shell_thickness": shell_thickness,
        "norm_thickness": norm_thickness,
        "delta_integral": delta_integral,
        "max_gradient": max_gradient,
        "r_inflection": r_inflection,
        "shell_area_fraction": shell_area_fraction,
        "enrichment_ratio": (c_peak / c_core) if c_core > 1e-6 else 1.0,
        "dc_dr": dc_dr
    }

def print_analytics_summary(metrics):
    """Prints a structured analytics report to console."""
    print("=" * 68)
    print(" LatticeForge: Radial Concentration & Shell Thickness Analytics")
    print("=" * 68)
    print(" Microstructure Core-Shell Segregation Metrics:")
    print(f"  * Bulk Core Ce Concentration (C_core)  : {metrics['c_core']:.4f} ({metrics['c_core']*100:.2f}%)")
    print(f"  * Boundary Peak Ce Conc. (C_peak)      : {metrics['c_peak']:.4f} ({metrics['c_peak']*100:.2f}%)")
    print(f"  * Segregation Enrichment Ratio         : {metrics['enrichment_ratio']:.2f}x")
    print(f"  * Half-Maximum Threshold (C_50)        : {metrics['c_thresh']:.4f} ({metrics['c_thresh']*100:.2f}%)")
    print(f"  * Inner Shell Boundary Radius (r_inner): {metrics['r_inner']:.2f} lattice units")
    print(f"  * Outer Shell Boundary Radius (r_outer): {metrics['r_outer']:.2f} lattice units")
    print("-" * 68)
    print(f"  >>> QUANTITATIVE SHELL THICKNESS (delta) : {metrics['shell_thickness']:.2f} lattice units")
    print(f"  * Normalized Shell Thickness (delta/R)  : {metrics['norm_thickness']*100:.1f}% of grain radius")
    print(f"  * Integral Breadth Thickness           : {metrics['delta_integral']:.2f} lattice units")
    print(f"  * Steepest Concentration Gradient      : {metrics['max_gradient']:.3f} lu^-1 (at r = {metrics['r_inflection']:.2f} lu)")
    print(f"  * Estimated Shell Area Fraction        : {metrics['shell_area_fraction']*100:.1f}%")
    print("=" * 68)

def plot_radial_profiles(r, c, std_err, norm_r, metrics, out_dir):
    """
    Renders high-aesthetic dual-panel publication-ready scientific figure:
      Panel 1: Absolute Radial Distance Profile with Annotated Shell Thickness
      Panel 2: Normalized Distance Profile with Interfacial Concentration Gradient
    """
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5.8), dpi=150)
    
    # ================= PANEL 1: Radial Profile =================
    # Discrete experimental/simulation points with error bars
    ax1.errorbar(
        r, c, yerr=std_err,
        fmt='o', markersize=5, color='#2c3e50', ecolor='#95a5a6',
        elinewidth=1.2, capsize=2.5, capthick=1.0, alpha=0.85,
        label=r'Discrete Measurement $\langle c(r) \rangle \pm \sigma$'
    )
    
    # Smooth spline interpolation curve
    if len(r) >= 4:
        r_dense = np.linspace(r[0], r[-1], 250)
        c_dense = np.interp(r_dense, r, c)
        ax1.plot(r_dense, c_dense, color='#d32f2f', linewidth=2.5, label='Radial Ce Profile $c(r)$')
    else:
        ax1.plot(r, c, color='#d32f2f', linewidth=2.5, label='Radial Ce Profile $c(r)$')
        
    # Shaded Core and Shell Regions
    ax1.axvspan(0.0, metrics['r_inner'], color='#e3f2fd', alpha=0.55, label='Nd-Rich Matrix Core')
    ax1.axvspan(metrics['r_inner'], metrics['r_outer'], color='#ffcdd2', alpha=0.60,
                label=rf'Boundary Shell ($\delta = {metrics["shell_thickness"]:.2f}$ lu)')
    
    # Threshold and Reference Lines
    ax1.axhline(metrics['c_thresh'], color='#e65100', linestyle='--', linewidth=1.5,
                label=rf'Half-Max Threshold $C_{{50}} = {metrics["c_thresh"]:.3f}$')
    ax1.axhline(metrics['c_core'], color='#1565c0', linestyle=':', linewidth=1.5,
                label=rf'Bulk Baseline $C_{{core}} = {metrics["c_core"]:.3f}$')
    
    # Inner and Outer Radii Markers
    ax1.axvline(metrics['r_inner'], color='#b71c1c', linestyle='-.', linewidth=1.2, alpha=0.7)
    ax1.axvline(metrics['r_outer'], color='#b71c1c', linestyle='-.', linewidth=1.2, alpha=0.7)
    
    # Shell Thickness Double-Headed Arrow Annotation
    y_arrow = metrics['c_thresh']
    ax1.annotate(
        '', xy=(metrics['r_inner'], y_arrow), xytext=(metrics['r_outer'], y_arrow),
        arrowprops=dict(arrowstyle='<->', color='#b71c1c', lw=2.2)
    )
    ax1.text(
        0.5 * (metrics['r_inner'] + metrics['r_outer']), y_arrow + 0.035,
        rf'$\mathbf{{\delta = {metrics["shell_thickness"]:.2f}}}$ lu',
        ha='center', va='bottom', fontsize=11, fontweight='bold', color='#b71c1c',
        bbox=dict(boxstyle='round,pad=0.25', facecolor='#ffffff', edgecolor='#b71c1c', alpha=0.9)
    )
    
    ax1.set_title("Radial Solute Segregation Profile (Lattice Distance)", fontsize=12, fontweight='bold', pad=12)
    ax1.set_xlabel("Radial Distance from Centroid $r$ (lattice units)", fontsize=11)
    ax1.set_ylabel(r"Solute Atomic Fraction $C_{\mathrm{Ce}}(r)$", fontsize=11)
    ax1.set_xlim(0, max(r) * 1.04)
    ax1.set_ylim(0, min(1.0, max(c) * 1.22))
    ax1.grid(True, linestyle='--', alpha=0.55)
    ax1.legend(loc='upper left', fontsize=8.5, framealpha=0.92)
    
    # ================= PANEL 2: Normalized & Gradient =================
    color_c = '#1976d2'
    ax2.plot(norm_r, c, color=color_c, linewidth=2.2, marker='s', markersize=4,
             label=r'Normalized Conc. $C(r / \bar{R})$')
    ax2.set_xlabel(r"Normalized Radial Distance $r / \bar{R}_{\mathrm{eff}}$", fontsize=11)
    ax2.set_ylabel(r"Solute Atomic Fraction $C_{\mathrm{Ce}}$", fontsize=11, color=color_c)
    ax2.tick_params(axis='y', labelcolor=color_c)
    ax2.set_xlim(0, max(norm_r) * 1.04)
    ax2.set_ylim(0, min(1.0, max(c) * 1.22))
    ax2.grid(True, linestyle='--', alpha=0.55)
    
    # Secondary Y-Axis for Concentration Gradient dC/dr
    ax2_twin = ax2.twinx()
    color_g = '#e65100'
    ax2_twin.plot(norm_r, metrics['dc_dr'], color=color_g, linewidth=2.0, linestyle='-',
                  marker='^', markersize=4, label=r'Interfacial Gradient $\nabla C = \frac{dC}{dr}$')
    ax2_twin.set_ylabel(r"Segregation Gradient $\frac{dC}{dr}$ ($\mathrm{lu}^{-1}$)", fontsize=11, color=color_g)
    ax2_twin.tick_params(axis='y', labelcolor=color_g)
    ax2_twin.set_ylim(min(-0.02, min(metrics['dc_dr']) * 1.2), max(0.1, max(metrics['dc_dr']) * 1.35))
    
    # Shaded Normalized Shell Region
    norm_r_inner = metrics['r_inner'] / (metrics['r_outer'] / norm_r[int(np.argmax(c))])
    norm_r_outer = norm_r[int(np.argmax(c))]
    ax2.axvspan(norm_r_inner, norm_r_outer, color='#ffe0b2', alpha=0.45,
                label=rf'Shell Zone ($\Delta r / R = {metrics["norm_thickness"]*100:.1f}\%$)')
    
    # Combine twin legends
    lines_1, labels_1 = ax2.get_legend_handles_labels()
    lines_2, labels_2 = ax2_twin.get_legend_handles_labels()
    ax2.legend(lines_1 + lines_2, labels_1 + labels_2, loc='upper left', fontsize=8.5, framealpha=0.92)
    ax2.set_title("Normalized Radial Segregation & Interfacial Gradient", fontsize=12, fontweight='bold', pad=12)
    
    plt.tight_layout()
    
    # Save outputs
    out_path = os.path.join(out_dir, 'radial_profile.png')
    plt.savefig(out_path, dpi=200, bbox_inches='tight')
    
    # Also save mirror for boundary_shell_profile.png
    alt_path = os.path.join(out_dir, 'boundary_shell_profile.png')
    plt.savefig(alt_path, dpi=200, bbox_inches='tight')
    plt.close()
    
    print(f"\n[+] Boundary shell profile saved to: {out_path}")
    print(f"[+] High-resolution analytical mirror: {alt_path}")

def main():
    root_dir, outputs_dir = get_project_paths()
    print(f"Loading radial concentration profile from outputs directory: {outputs_dir}...")
    
    r, c, counts, std_err, norm_r = load_or_generate_radial_profile(outputs_dir, root_dir)
    
    if len(r) == 0:
        print("Error: No data points found in radial profile!", file=sys.stderr)
        sys.exit(1)
        
    metrics = calculate_shell_thickness_quantitative(r, c, counts, norm_r)
    print_analytics_summary(metrics)
    plot_radial_profiles(r, c, std_err, norm_r, metrics, outputs_dir)

if __name__ == "__main__":
    main()
